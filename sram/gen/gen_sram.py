#!/usr/bin/env python3
"""
Generator for the 256x1 SRAM (16x16 6T array) top-level netlist and test benches.

Pins (all through bond wire + pad models):
  CLK   - clock
  ADDR  - serial address bit, shifted into an 8-bit register on every rising edge
          (MSB first; register = last 8 bits received; row = A[7:4], col = A[3:0])
  RW    - 1 = write, 0 = read (sampled on rising edge, applies to that cycle)
  DIN   - write data (sampled on rising edge)
  DOUT  - read data, valid one cycle after the read access

Cycle k: rising edge k captures ADDR/RW/DIN -> CLK high: decode + precharge
         -> CLK low: wordline on, read or write -> rising edge k+1 captures read data.
"""
import argparse, random
import sys, os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paths import ROOT, CELLS, SIM, PLOTS, PDK_LIB

CORE = "vdd"
IO = "vddio"

def de_bruijn(k, n):
    a = [0] * k * n
    seq = []
    def db(t, p):
        if t > n:
            if n % p == 0:
                seq.extend(a[1:p + 1])
        else:
            a[t] = a[t - p]
            db(t + 1, p)
            for j in range(a[t - p] + 1, k):
                a[t] = j
                db(t + 1, t)
    db(1, 1)
    return seq


def netlist_core(wire=True):
    L = []
    w = L.append
    w("* ===== 256x1 SRAM core + I/O (generated by gen_sram.py) =====")
    w(".subckt sram256 CLK ADDR RW DIN DOUT vdd vddio vss")
    # ---------------- pads + input buffers
    for p in ["CLK", "ADDR", "RW", "DIN"]:
        w(f"Xpad_{p} {p} {p.lower()}_pad vddio vss bondpad")
        w(f"Xib_{p} {p.lower()}_pad {p.lower()}_in vdd vss inbuf")
    w("Xpad_DOUT DOUT dout_pad vddio vss bondpad")
    # ---------------- clock tree
    w("* --- clock distribution: root buffer + 3 balanced branches")
    w("Xck_r1 clk_in ckr_b vdd vss inv wn=1.68 wp=3.36")
    w("Xck_r2 ckr_b ckr vdd vss inv wn=3.36 wp=6.72")
    # branch A : flip-flop clock (non-inverting, 2 stages)
    w("Xck_a1 ckr cka_b vdd vss inv wn=0.84 wp=1.68")
    w("Xck_a2 cka_b clk_ff vdd vss inv wn=1.68 wp=3.36")
    # branch B : inverted clock for wordline / write enable (3 stages)
    w("Xck_b1 ckr ckb1 vdd vss inv wn=0.84 wp=1.68")
    w("Xck_b2 ckb1 ckb2 vdd vss inv wn=1.26 wp=2.52")
    w("Xck_b3 ckb2 clkb vdd vss inv wn=2.52 wp=5.04")
    # branch C : precharge pulse, pcb = NAND(ck, ck_delayed): turns off fast at CLK fall,
    # turns on late after CLK rise (hold margin for read data capture)
    # 8-inverter delay: precharge must start only after the wordline has closed
    prev = "ckr"
    for i in range(1, 9):
        nxt = "ckd" if i == 8 else f"d{i}"
        w(f"Xck_d{i} {prev} {nxt} vdd vss inv")
        prev = nxt
    w("Xck_c1 ckr ckd pc0 vdd vss nand2 wn=1.68 wp=1.68")
    w("Xck_c2 pc0 pc1 vdd vss inv wn=0.84 wp=1.68")
    w("Xck_c3 pc1 pcb vdd vss inv wn=2.52 wp=5.04")
    # ---------------- input registers
    w("* --- serial address shift register (a0 = newest bit, a7 = oldest = MSB)")
    w("Xff_a0 addr_in clk_ff a0 ab0 vdd vss dff")
    for i in range(1, 8):
        w(f"Xff_a{i} a{i-1} clk_ff a{i} ab{i} vdd vss dff")
    w("Xff_rw rw_in clk_ff rwq rwqb vdd vss dff")
    w("Xff_din din_in clk_ff dinq dinqb vdd vss dff")
    # ---------------- predecoders (2:4) x4
    def bit(k, v):
        return f"a{k}" if v else f"ab{k}"
    for name, (hi, lo) in {"rh": (7, 6), "rl": (5, 4), "ch": (3, 2), "cl": (1, 0)}.items():
        for k in range(4):
            w(f"Xpd_{name}{k} {bit(hi, k >> 1)} {bit(lo, k & 1)} {name}b{k} vdd vss nand2")
            w(f"Xpi_{name}{k} {name}b{k} {name}{k} vdd vss inv wn=0.84 wp=1.68")
    # ---------------- row decoder + wordline drivers
    w("* --- row decoder: WL_r = rh & rl & clkb")
    for r in range(16):
        w(f"Xrd{r} rh{r >> 2} rl{r & 3} clkb wlb{r} vdd vss nand3")
        w(f"Xwd{r} wlb{r} wl{r} vdd vss inv wn=0.84 wp=1.68")
        if wire:
            w(f"Cwl{r} wl{r} vss 4f")
    # ---------------- column decoder
    w("* --- column decoder")
    for c in range(16):
        w(f"Xcd{c} ch{c >> 2} cl{c & 3} cselb{c} vdd vss nand2")
        w(f"Xcs{c} cselb{c} csel{c} vdd vss inv wn=0.84 wp=1.68")
    # ---------------- array + column periphery
    w("* --- 16x16 bit-cell array")
    for r in range(16):
        for c in range(16):
            w(f"Xc_{r}_{c} bl{c} blb{c} wl{r} vdd vss bitcell")
    for c in range(16):
        w(f"Xpre{c} bl{c} blb{c} pcb vdd precharge")
        w(f"Xmux{c} bl{c} blb{c} dl dlb csel{c} vss colmux")
        if wire:
            w(f"Cbl{c} bl{c} vss 5f")
            w(f"Cblb{c} blb{c} vss 5f")
    # ---------------- write enable + shared read/write circuit
    w("Xwe1 rwq clkb web vdd vss nand2")
    w("Xwe2 web we vdd vss inv wn=1.26 wp=2.52")
    w("Xrw dl dlb we dinq dinqb pcb rd vdd vss rwckt")
    if wire:
        w("Cdl dl vss 10f")
        w("Cdlb dlb vss 10f")
    # ---------------- output register + pad driver (I/O supply)
    w("Xff_out rd clk_ff rdq rdqb vdd vss dff")
    w("Xob rdqb dout_pad vddio vss outbuf")
    w(".ends sram256")
    return "\n".join(L)


def make_stream(kind, ncyc=None, seed=1):
    """Return list of (addr_bit, rw, din) per cycle and the expected-read list."""
    rnd = random.Random(seed)
    data = {a: rnd.randint(0, 1) for a in range(256)}
    cyc = []
    if kind == "full":
        s = de_bruijn(2, 8)          # cyclic, every 8-bit window appears once
        stream = s + s + s[:16]
        for k, b in enumerate(stream):
            cyc.append([b, 0, 0])
        # write phase: cycles 7..262, read phase: 263..518
        for k in range(len(cyc)):
            if 7 <= k <= 262:
                cyc[k][1] = 1
    elif kind == "smoke":
        # write 4 addresses then read them back (8 cycles each, protocol: rw=1 on last bit)
        addrs = [(0x00, 1), (0xFF, 1), (0x5A, 0), (0xA5, 1), (0x00, None), (0xFF, None), (0x5A, None), (0xA5, None), (0x0F, 0), (0x0F, None)]
        for a, d in addrs:
            bits = [(a >> (7 - i)) & 1 for i in range(8)]
            for i, b in enumerate(bits):
                last = i == 7
                cyc.append([b, 1 if (last and d is not None) else 0, d if (last and d is not None) else 0])
        data = None
    elif kind.startswith("rand"):
        # random every-cycle traffic: sliding address, random R/W and data
        n = int(kind[4:] or 64)
        r2 = random.Random(seed + 7)
        for k in range(n):
            cyc.append([r2.randint(0, 1), 1 if (k >= 8 and r2.random() < 0.4) else 0, r2.randint(0, 1)])
    # reference model (initial array contents = the .nodeset power-up state)
    reg = [None] * 8
    mem = dict(init_mem())
    if data is not None and kind == "full":
        pass
    exp = []  # (cycle index of access, expected bit) for reads where address & data are known
    for k, (b, rw, din) in enumerate(cyc):
        reg = reg[1:] + [b]
        known = None not in reg
        A = sum(bit << (7 - i) for i, bit in enumerate(reg)) if known else None
        if kind == "full" and rw == 1:
            din = data[A]
            cyc[k][2] = din
        if rw == 1 and known:
            mem[A] = din
        elif rw == 0 and known and A in mem:
            exp.append((k, mem[A], A))
    return cyc, exp


def init_mem():
    rnd = random.Random(99)
    m = {}
    for r in range(16):
        for c in range(16):
            m[r * 16 + c] = rnd.randint(0, 1)
    return m


def pwl(name, node, values, T, tr, vdd=1.8):
    # value for cycle k is applied at t = k*T (mid-way between rising edges at k*T + T/2)
    pts = [(0, values[0])]
    for k in range(1, len(values)):
        if values[k] != values[k - 1]:
            t = k * T
            pts.append((t, values[k - 1]))
            pts.append((t + tr, values[k]))
    s = " ".join(f"{t:.4e} {v * vdd:.2f}" for t, v in pts)
    return f"V{name} {node}_src 0 PWL({s})\nR{name} {node}_src {node} 50"


def testbench(kind, T, tr=50e-12, cload=5e-12, wire=True, extra_cycles=2, nodeset=True, seed=1, corner="tt"):
    cyc, exp = make_stream(kind, seed=seed)
    n = len(cyc) + extra_cycles
    vals = cyc + [[0, 0, 0]] * extra_cycles
    L = [f"* SRAM256 testbench: {kind}, T={T*1e9:.3f} ns",
         f".lib {PDK_LIB} {corner}",
         f".include {CELLS}",
         netlist_core(wire),
         "Vdd vdd 0 1.8", "Vddio vddio 0 1.8",
         f"Vclk clk_src 0 PULSE(0 1.8 {T/2:.4e} {tr:.2e} {tr:.2e} {T/2-tr:.4e} {T:.4e})",
         "Rclk clk_src CLK 50",
         pwl("addr", "ADDR", [v[0] for v in vals], T, tr),
         pwl("rw", "RW", [v[1] for v in vals], T, tr),
         pwl("din", "DIN", [v[2] for v in vals], T, tr),
         f"Cload DOUT 0 {cload:.3e}",
         "Xdut CLK ADDR RW DIN DOUT vdd vddio 0 sram256"]
    if nodeset:
        im = init_mem()
        ns = []
        for r in range(16):
            for c in range(16):
                v = im[r * 16 + c] * 1.8
                ns.append(f"v(xdut.xc_{r}_{c}.q)={v} v(xdut.xc_{r}_{c}.qb)={1.8 - v}")
        for i in range(0, len(ns), 8):
            L.append(".ic " + " ".join(ns[i:i + 8]))
    tstop = n * T + T / 2
    L += [".option reltol=1e-3",
          f".tran {T/50:.3e} {tstop:.4e}",
          ".save v(CLK) v(ADDR) v(RW) v(DIN) v(DOUT) v(xdut.rdqb) v(xdut.rd) v(xdut.dl) v(xdut.dlb) v(xdut.pcb) v(xdut.clkb) v(xdut.clk_ff) v(xdut.we) v(xdut.wl0) v(xdut.wl15) v(xdut.bl0) v(xdut.blb0) v(xdut.bl15) v(xdut.blb15) v(xdut.xc_0_0.q) v(xdut.xc_15_15.q) i(Vdd) i(Vddio)",
          ".end"]
    return "\n".join(L), cyc, exp, tstop


